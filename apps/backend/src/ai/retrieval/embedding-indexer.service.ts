import { Inject, Injectable, Logger } from '@nestjs/common';
import type { Prisma } from '@prisma/client';
import { PrismaService } from '../../database/prisma.service';
import { LLM_PROVIDER } from '../llm/llm-provider.interface';
import type { LlmProvider } from '../llm/llm-provider.interface';

export type IndexableContentType =
  | 'TASK'
  | 'PROJECT'
  | 'NOTE'
  | 'COMMENT'
  | 'HABIT';

/**
 * MVP single-chunk limit: content is truncated to this many chars before
 * embedding. Multi-chunk indexing is a future extension.
 */
const MAX_CHUNK_CHARS = 8000;

/**
 * Writes and removes content embeddings (ODD 004 S2).
 *
 * Indexing NEVER breaks the domain write that triggered it: every method
 * swallows failures with a warning log.
 */
@Injectable()
export class EmbeddingIndexerService {
  private readonly logger = new Logger(EmbeddingIndexerService.name);

  constructor(
    private readonly prisma: PrismaService,
    @Inject(LLM_PROVIDER) private readonly llm: LlmProvider,
  ) {}

  async indexContent(
    contentType: IndexableContentType,
    contentId: string,
    text: string,
    metadata?: Prisma.InputJsonValue,
  ): Promise<void> {
    try {
      const content = text.slice(0, MAX_CHUNK_CHARS);
      const [vector] = await this.llm.embed([content]);
      if (!vector?.length) {
        this.logger.warn(
          `Empty embedding for ${contentType} ${contentId}; skipping index`,
        );
        return;
      }

      await this.prisma.aiEmbedding.upsert({
        where: {
          contentType_contentId_chunkIndex: {
            contentType,
            contentId,
            chunkIndex: 0,
          },
        },
        create: {
          contentType,
          contentId,
          chunkIndex: 0,
          content,
          ...(metadata !== undefined ? { metadata } : {}),
        },
        update: {
          content,
          ...(metadata !== undefined ? { metadata } : {}),
        },
      });

      // `embedding` is Unsupported("vector(768)"): Prisma cannot write it via
      // create/update, so the vector is set with raw SQL afterwards.
      await this.prisma.$executeRaw`
        UPDATE "AiEmbedding"
        SET "embedding" = ${toVectorLiteral(vector)}::vector, "updatedAt" = NOW()
        WHERE "contentType" = ${contentType}
          AND "contentId" = ${contentId}
          AND "chunkIndex" = 0
      `;
    } catch (error) {
      this.logger.warn(
        `Failed to index ${contentType} ${contentId}: ${(error as Error).message}`,
      );
    }
  }

  async removeContent(
    contentType: IndexableContentType,
    contentId: string,
  ): Promise<void> {
    try {
      await this.prisma.aiEmbedding.deleteMany({
        where: { contentType, contentId },
      });
    } catch (error) {
      this.logger.warn(
        `Failed to remove index for ${contentType} ${contentId}: ${(error as Error).message}`,
      );
    }
  }
}

/**
 * Serializes a vector to the postgres `'[v,v,...]'` literal. Values are
 * coerced through Number and must be finite (defensive: the floats are
 * generated by us, never user input).
 */
function toVectorLiteral(vector: number[]): string {
  const safe = vector.map((v) => {
    const n = Number(v);
    if (!Number.isFinite(n)) {
      throw new Error('Non-finite embedding value');
    }
    return n;
  });
  return `[${safe.join(',')}]`;
}
